local root=...
local make=assert(loadfile(root.."/qa/softres/improvements_client.lua"))(root,root)
local a,e,s=make("Leader-Realm")
local count=0;local function check(value,message) count=count+1;assert(value,message) end
a:BuildUI()
check(a.ui.start:GetText()=="Loot Council" and a.ui.softResStart:GetText()=="SoftRes","session start choices missing")
check(a:RaidProfileLabel()=="Custom setup","unprofiled setup had a profile label")
assert(a:SaveProfile("Progression"))
check(a:RaidProfileLabel()=="Progression","saving profile did not select it")
assert(a:Act("responseDuration",{seconds=90,duration=90}))
local name,modified=a:RaidProfileInfo()
check(name=="Progression" and modified,"editing setup lost profile provenance or modified flag")
assert(a:LoadProfile("Progression"))
check(a:RaidProfileLabel()=="Progression","loading profile did not clear modified flag")
a.ui.start:GetScript("OnClick")()
check(a.ui.lootCouncilStart:IsShown() and not a.state and not s.session,"opening Loot Council started a session")
check(a.ui.lootCouncilStartSummary:GetText():find("Progression",1,true),"start popup omitted current profile")
a.ui.lootCouncilStart:Hide()
check(not a.state and not s.session,"cancelling start popup started a run")
-- Load and review a profile without starting a session.
a:ShowLootCouncilStart();a.ui.lootCouncilStart.selectedProfile="Progression"
a.ui.lootCouncilApplyProfile:GetScript("OnClick")()
check(not a.state and a.ui.lootCouncilQuickStart:GetText()=="Start Session","loading a profile started immediately or omitted the final start action")
a.ui.lootCouncilQuickStart:GetScript("OnClick")()
check(a.state and a.state.raidProfileName=="Progression" and not a.state.raidProfileModified and not s.session,"quick start lost selected profile or chose SoftRes")
check(not a.ui.lootCouncilStart:IsShown() and not a.ui.softResStart:IsEnabled(),"active Loot Council left conflicting start controls enabled")
check(a:RaidProfileLabel()=="Progression","active session lost its starting profile")
assert(a:Act("responseDuration",{duration=95}))
check(a:RaidProfileLabel():find("Progression",1,true) and select(2,a:RaidProfileInfo()),"active setup edits did not flag the starting profile as modified")

assert(a:Act("end"))
a.ui.softResStart:GetScript("OnClick")()
check(s.setup and s.setup:IsShown() and not a.state and not s.session,"SoftRes button bypassed content selection")
print("SESSION START PASS: "..count.." checks; mode buttons, profile provenance, modified state, confirmation and content selection")
